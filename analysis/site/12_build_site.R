# Nothing is computed here, so the page always says what the paper says. Run after
# 11_paper_inputs.R and the paper build. GitHub Pages publishes site/
# (.github/workflows/pages.yml).
# Usage (from the repository root): Rscript analysis/site/12_build_site.R

tex <- readLines("paper/generated/numbers.tex", encoding = "UTF-8")
tex <- grep("^\\\\newcommand", tex, value = TRUE)
keys <- sub("^\\\\newcommand\\{\\\\([A-Za-z]+)\\}.*$", "\\1", tex)
vals <- sub("^\\\\newcommand\\{\\\\[A-Za-z]+\\}\\{(.*)\\}$", "\\1", tex)
# LaTeX -> HTML: thin-space thousands separator, "$<$", en dash, escaped symbols
vals <- gsub("\\\\,", ",", vals)
vals <- gsub("\\$<\\$", "&lt;", vals)
vals <- gsub("--", "&ndash;", vals, fixed = TRUE)
vals <- gsub("\\\\([&%_])", "\\1", vals)
vals <- gsub("&(?![a-z]+;)", "&amp;", vals, perl = TRUE)
num <- setNames(vals, keys)

html <- paste(readLines("analysis/site/template.html", encoding = "UTF-8"), collapse = "\n")
html <- sub("<!-- Template of the project page.*?-->\n", "", html)
tags <- unique(regmatches(html, gregexpr("\\{\\{[A-Za-z]+(\\|p)?\\}\\}", html))[[1]])
for (t in tags) {
  key <- sub("^\\{\\{([A-Za-z]+).*$", "\\1", t)
  if (!key %in% names(num)) stop("No macro \\", key, " in paper/generated/numbers.tex")
  v <- num[[key]]
  if (grepl("|p", t, fixed = TRUE)) v <- if (startsWith(v, "&lt;")) paste("p &lt;", sub("^&lt;", "", v)) else paste("p =", v)
  html <- gsub(t, v, html, fixed = TRUE)
}
stopifnot(!grepl("{{", html, fixed = TRUE))

dir.create("site/figures", recursive = TRUE, showWarnings = FALSE)
html <- paste0("<!-- Generated by analysis/site/12_build_site.R from analysis/site/template.html. Do not edit. -->\n", html)
writeLines(html, "site/index.html", useBytes = TRUE)
if (!file.copy("paper/main.pdf", "site/paper.pdf", overwrite = TRUE)) stop("paper/main.pdf not found: build the paper first")
figs <- regmatches(html, gregexpr("figures/[a-z_]+\\.png", html))[[1]]
missing <- figs[!file.exists(file.path("site", figs))]
if (length(missing)) stop("Missing figures (run analysis/paper/11_paper_inputs.R): ", paste(missing, collapse = ", "))
invisible(file.create("site/.nojekyll"))
cat(sprintf("Wrote site/index.html (%d values filled), site/paper.pdf and %d figures.\n", length(tags), length(unique(figs))))
